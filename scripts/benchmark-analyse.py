#!/usr/bin/env python3
"""Turn benchmark trials into the published results section.

Reads research/benchmark/results.ndjson and writes the results portion of
content/pages/benchmark.md between two markers. Everything outside the markers
is hand-written and is never touched.

With no trials it emits an explicit "nothing has been measured" block. That is
the important behaviour: the page must be incapable of implying a result it does
not have, so the empty state is generated by the same code path as a full one
rather than being a thing someone remembers to write.

Charts are inline SVG built from the rows — no library, no CDN, and nothing is
drawn for a cell with no data. A missing bar reads as missing; a zero-height bar
would read as a measured zero.

Usage:
  benchmark-analyse.py               rewrite the results section
  benchmark-analyse.py --stdout      print it instead
  benchmark-analyse.py --self-test   prove the empty and partial states
"""
import argparse
import collections
import html
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
STORE = os.path.join(ROOT, "research", "benchmark", "results.ndjson")
PAGE = os.path.join(ROOT, "content", "pages", "benchmark.md")
START = "<!-- BENCHMARK-RESULTS:START -->"
END = "<!-- BENCHMARK-RESULTS:END -->"

PLATFORMS = ("shopify", "wordpress", "astro", "nextjs", "static")
LABEL = {"shopify": "Shopify", "wordpress": "WordPress", "astro": "Astro",
         "nextjs": "Next.js", "static": "Static"}
MIN_RUNS = 3          # stated in METHODOLOGY.md; a cell below this is not published


def load(path=STORE):
    if not os.path.exists(path):
        return []
    out = []
    for line in open(path, encoding="utf-8"):
        line = line.strip()
        if line:
            out.append(json.loads(line))
    return [r for r in out if r.get("ended_at")]


def bar_chart(title, pairs, unit=""):
    """Inline SVG. `pairs` is [(label, value or None)]. None draws no bar."""
    have = [(l, v) for l, v in pairs if v is not None]
    if not have:
        return ""
    top = max(v for _l, v in have) or 1
    w, rowh, pad, labw = 560, 26, 8, 130
    h = pad * 2 + rowh * len(pairs)
    parts = ['<figure class="sbs-chart">',
             '<figcaption>%s</figcaption>' % html.escape(title),
             '<svg viewBox="0 0 %d %d" role="img" aria-label="%s" width="100%%">'
             % (w, h, html.escape(title))]
    for i, (label, v) in enumerate(pairs):
        y = pad + i * rowh
        parts.append('<text x="0" y="%d" font-size="12" fill="currentColor">%s</text>'
                     % (y + 14, html.escape(label)))
        if v is None:
            parts.append('<text x="%d" y="%d" font-size="12" fill="currentColor" '
                         'opacity=".6">not measured</text>' % (labw, y + 14))
            continue
        bw = int((v / float(top)) * (w - labw - 60))
        parts.append('<rect x="%d" y="%d" width="%d" height="14" rx="3" '
                     'fill="currentColor" opacity=".75"></rect>'
                     % (labw, y + 4, max(bw, 1)))
        parts.append('<text x="%d" y="%d" font-size="12" fill="currentColor">%s%s</text>'
                     % (labw + max(bw, 1) + 6, y + 14, v, unit))
    parts += ['</svg>', '</figure>']
    return "\n".join(parts)


def summarise(rows):
    by = collections.defaultdict(list)
    for r in rows:
        by[(r["platform"], r["task_id"])].append(r)
    return by


def render(rows):
    if not rows:
        return "\n".join([
            START, "",
            "## Results", "",
            "**Nothing has been measured yet. There are no results on this page, and "
            "no figure below should be cited, because there are none.**", "",
            "The methodology, the task list and the data schema are published first, "
            "on purpose. They are the part worth arguing with, and criticism of a "
            "method is only useful before the data exists — afterwards it is very "
            "hard to tell a genuine methodological objection from a dislike of the "
            "result.", "",
            "The dataset is `research/benchmark/results.csv` in the public "
            "repository. It currently contains a header row and nothing else.", "",
            "When trials run, this section is regenerated by "
            "`scripts/benchmark-analyse.py` from the raw rows. It is not written by "
            "hand, so the page cannot say something the dataset does not.", "",
            END])

    by = summarise(rows)
    tasks = sorted({r["task_id"] for r in rows})
    total = len(rows)
    complete = [t for t in tasks
                if all(len(by.get((p, t), [])) >= MIN_RUNS for p in PLATFORMS)]

    out = [START, "", "## Results", "",
           "%d trial(s) recorded. %d of %d task(s) have the full %d runs on all "
           "five platforms and are reported below; the rest are withheld until "
           "they do, because a partial row invites the comparison the missing "
           "cell would change."
           % (total, len(complete), len(tasks), MIN_RUNS), ""]

    if not complete:
        out += ["No task is complete across all five platforms yet, so no "
                "comparison is published.", "", END]
        return "\n".join(out)

    models = sorted({r["model"] for r in rows})
    versions = sorted({r["tool_version"] for r in rows})
    dates = sorted({(r.get("ended_at") or "")[:10] for r in rows if r.get("ended_at")})
    out += ["| | |", "| --- | --- |",
            "| Model(s) | %s |" % ", ".join(models),
            "| Claude Code version(s) | %s |" % ", ".join(versions),
            "| Dates tested | %s to %s |" % (dates[0], dates[-1]), ""]

    for t in complete:
        title = next((r.get("task_title") for r in rows if r["task_id"] == t), t)
        out += ["### %s — %s" % (t, title), "",
                "| Platform | Runs | Succeeded | Interventions (min–max) | Lighthouse SEO |",
                "| --- | ---: | ---: | ---: | ---: |"]
        succ_pairs, iv_pairs = [], []
        for p in PLATFORMS:
            cell = by.get((p, t), [])
            n = len(cell)
            s = sum(1 for r in cell if r.get("success"))
            ivs = [r.get("human_interventions") or 0 for r in cell]
            seo = [r["lighthouse_seo"] for r in cell if r.get("lighthouse_seo") is not None]
            out.append("| %s | %d | %d | %s | %s |" % (
                LABEL[p], n, s,
                ("%d–%d" % (min(ivs), max(ivs))) if ivs else "—",
                ("%d–%d" % (min(seo), max(seo))) if seo else "not measured"))
            succ_pairs.append((LABEL[p], s))
            iv_pairs.append((LABEL[p], max(ivs) if ivs else None))
        out += ["",
                bar_chart("%s — trials succeeded out of %d" % (t, MIN_RUNS), succ_pairs),
                "",
                bar_chart("%s — most corrections needed in any run" % t, iv_pairs),
                "",
                "Ranges, not means. Where three runs disagree, the disagreement is "
                "the finding.", ""]

    out += ["Every figure above is traceable to a row in "
            "`research/benchmark/results.csv`.", "", END]
    return "\n".join(out)


def splice(text, section):
    if START not in text or END not in text:
        raise SystemExit("markers not found in %s" % PAGE)
    a = text.index(START)
    b = text.index(END) + len(END)
    return text[:a] + section + text[b:]


def self_test():
    ok, bad = [], []

    def check(name, got, want):
        (ok if got == want else bad).append("%s: got %r want %r" % (name, got, want))

    empty = render([])
    check("empty state says nothing has been measured",
          "Nothing has been measured yet" in empty, True)
    check("empty state draws no chart", "<svg" in empty, False)
    check("empty state states no number of trials", "trial(s) recorded" in empty, False)

    def trial(p, t, run, success=True, iv=0, seo=90):
        return {"platform": p, "task_id": t, "run": run, "success": success,
                "human_interventions": iv, "lighthouse_seo": seo,
                "task_title": "Ship a page", "model": "claude-opus-5",
                "tool_version": "2.1.0", "ended_at": "2026-09-07T00:00:00+00:00"}

    partial = [trial("astro", "T-01", i) for i in (1, 2, 3)]
    r = render(partial)
    check("a task on one platform is not published",
          "No task is complete across all five platforms" in r, True)
    check("partial state draws no chart", "<svg" in r, False)

    full = [trial(p, "T-01", i) for p in PLATFORMS for i in (1, 2, 3)]
    r = render(full)
    check("a complete task is published", "### T-01" in r, True)
    check("a complete task draws charts", r.count("<svg") == 2, True)
    check("two runs per platform is still withheld",
          "No task is complete" in render([t for t in full if t["run"] < 3]), True)

    # A measurement that was never taken must not draw a zero-height bar.
    nomeasure = [dict(t, lighthouse_seo=None) for t in full]
    r = render(nomeasure)
    check("an unmeasured column says so", "not measured" in r, True)
    check("charts still drawn for the fields that were measured",
          r.count("<svg") >= 1, True)
    check("a chart with no data at all renders nothing",
          bar_chart("x", [("a", None), ("b", None)]), "")

    for l in ok:
        print("  ok   %s" % l)
    for l in bad:
        print("  FAIL %s" % l)
    print("\n%d passed, %d failed" % (len(ok), len(bad)))
    return 1 if bad else 0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--stdout", action="store_true")
    ap.add_argument("--self-test", action="store_true")
    a = ap.parse_args()
    if a.self_test:
        raise SystemExit(self_test())
    rows = load()
    section = render(rows)
    if a.stdout:
        print(section)
        return 0
    text = open(PAGE, encoding="utf-8").read()
    open(PAGE, "w", encoding="utf-8").write(splice(text, section))
    print("%d trial(s); results section rewritten in %s"
          % (len(rows), os.path.relpath(PAGE, ROOT)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
